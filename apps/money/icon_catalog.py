APOSTROPHES = str.maketrans({"ʼ": "'", "’": "'", "`": "'"})


def words_of(text):
    return text.lower().translate(APOSTROPHES).replace("-", " ").split()


def tags_of(name):
    return words_of(name) + CATALOG[name].split()


def search(query, limit=40):
    words = words_of(query)
    if not words:
        return list(CATALOG)[:limit]
    found = [
        name for name in CATALOG
        if all(any(tag.startswith(word) for tag in tags_of(name)) for word in words)
    ]
    return found[:limit]


def suggest(name):
    stems = [word[: max(3, len(word) - 2)] for word in words_of(name) if len(word) >= 3]
    best, best_score = "", 0
    for icon in CATALOG:
        tags = CATALOG[icon].split()
        score = sum(1 for stem in stems if any(tag.startswith(stem) for tag in tags))
        if score > best_score:
            best, best_score = icon, score
    return best


def choices(name="", query="", picked=""):
    suggested = suggest(name or "")
    items = [icon for icon in dict.fromkeys([picked, suggested]) if icon]
    items += [icon for icon in search(query or "") if icon not in items]
    return {"items": items, "selected": picked or suggested, "query": query}
